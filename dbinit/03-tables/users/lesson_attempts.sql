-- =============================================================================
-- users.lesson_attempts
-- Depends on: auth.users, users.tutorial_lessons
-- -----------------------------------------------------------------------------
-- One row per lesson run. users.start_lesson creates it (started_at,
-- berlin_day = Europe/Berlin day of the start, used for the daily attempt
-- limit); users.complete_lesson fills completed_at, score, passed and
-- xp_awarded exactly once. Written only by the SECURITY DEFINER workers
-- users.record_lesson_start / users.record_lesson_completion.
-- =============================================================================

CREATE TABLE IF NOT EXISTS users.lesson_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      uuid        NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  lesson_id    text        NOT NULL REFERENCES users.tutorial_lessons (id) ON DELETE CASCADE,
  started_at   timestamptz NOT NULL DEFAULT now(),
  berlin_day   date        NOT NULL,
  completed_at timestamptz,
  score        numeric     CHECK (score BETWEEN 0 AND 1),
  passed       boolean,
  xp_awarded   integer     NOT NULL DEFAULT 0 CHECK (xp_awarded >= 0),
  CONSTRAINT lesson_attempts_completed CHECK (
       (completed_at IS NULL     AND score IS NULL     AND passed IS NULL)
    OR (completed_at IS NOT NULL AND score IS NOT NULL AND passed IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_lesson_attempts_user_day    ON users.lesson_attempts (user_id, berlin_day);
CREATE INDEX IF NOT EXISTS idx_lesson_attempts_user_lesson ON users.lesson_attempts (user_id, lesson_id);
