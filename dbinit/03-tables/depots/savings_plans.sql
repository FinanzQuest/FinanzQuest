-- =============================================================================
-- depots.savings_plans
-- Depends on: depots.depots, api.assets (FKs),
--             public.SavingsPeriod (02-types/savings_period.sql)
-- =============================================================================

CREATE TABLE IF NOT EXISTS depots.savings_plans (
  id           bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  depot_id     bigint         NOT NULL,
  asset_id     bigint         NOT NULL,
  worth        real           NOT NULL,
  period       SavingsPeriod  NOT NULL,
  created      timestamp      NOT NULL,
  last_changed timestamp      NOT NULL,
  last_executed date          DEFAULT NULL,
  created_by   uuid           NOT NULL,
  CONSTRAINT Savings_pkey       PRIMARY KEY (asset_id, depot_id),
  CONSTRAINT Savings_depot_fkey FOREIGN KEY (depot_id) REFERENCES depots.depots (id) ON DELETE CASCADE,
  CONSTRAINT Savings_stock_fkey FOREIGN KEY (asset_id) REFERENCES api.assets (id)
);

CREATE INDEX IF NOT EXISTS idx_savings_assets_depot ON depots.savings_plans (asset_id, depot_id);
CREATE INDEX IF NOT EXISTS idx_savings_asset         ON depots.savings_plans (asset_id);
CREATE INDEX IF NOT EXISTS idx_savings_depot         ON depots.savings_plans (depot_id);
