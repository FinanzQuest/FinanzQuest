-- depots.depots
-- Trigger depots.grant_default_budget is defined in
-- 07-triggers/depots/grant_default_budget.sql
-- cash is derived state: depots.apply_ledger_delta keeps it equal to
-- cash_start - SUM(expenses + commission) over the depot's transactions, so
-- buy_asset can check it under the depot row lock. Never written elsewhere.
-- =============================================================================

CREATE TABLE IF NOT EXISTS depots.depots (
  created    timestamp NOT NULL,
  cash       numeric   NOT NULL,  -- = cash_start - spent; maintained by the ledger trigger
  cash_start bigint    NOT NULL,
  users      uuid[]    NOT NULL,
  id         bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  -- shown to users instead of the id; chosen at creation or random
  name       text      NOT NULL DEFAULT depots.random_depot_name()
             CONSTRAINT depots_name_length CHECK (char_length(btrim(name)) BETWEEN 1 AND 40),
  CONSTRAINT Depots_pkey PRIMARY KEY (id)
);
