-- =============================================================================
-- api.funds
-- Depends on: nothing (api.assets.fund_id references it)
-- -----------------------------------------------------------------------------
-- One row per fund (share class), shared by all its listings in api.assets
-- (e.g. EUNL.DE, IWDA.AS and SWDA.L are one fund). Facts that rarely change
-- (ISIN, TER, index, replication, payout, domicile) are maintained by hand
-- (seed/funds.sql, migrations). The updater (`--mode details`) writes
-- fund_size, holdings_count, details_as_of and fills ter/inception only where
-- they are still NULL.
-- ter and weights are fractions: 0.0020 = 0.20 %.
-- details_source: the provider's locator (holdings CSV or product page URL);
-- NULL for funds whose details come from Yahoo (via a listing's symbol).
-- =============================================================================

CREATE TABLE api.funds (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isin             text UNIQUE
                   CONSTRAINT funds_isin_format CHECK (isin ~ '^[A-Z]{2}[A-Z0-9]{9}[0-9]$'),
  name             text NOT NULL,
  issuer           text NOT NULL,
  index_name       text,
  ter              numeric(6,5) CONSTRAINT funds_ter_range CHECK (ter >= 0 AND ter < 0.05),
  replication      text CONSTRAINT funds_replication CHECK (replication IN ('full', 'sampling', 'physical', 'synthetic')),
  distribution     text CONSTRAINT funds_distribution CHECK (distribution IN ('accumulating', 'distributing')),
  domicile         char(2),
  currency         char(3),
  inception        date,
  details_source   text,
  fund_size        numeric CONSTRAINT funds_fund_size_positive CHECK (fund_size > 0),
  holdings_count   integer CONSTRAINT funds_holdings_count_positive CHECK (holdings_count > 0),
  details_as_of    date,
  details_updated_at timestamptz
);
